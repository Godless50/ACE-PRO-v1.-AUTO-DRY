#pragma once
#include <stdint.h>

namespace rhcore {

// Показание датчика Xiaomi LYWSD03MMC.
//
// Значения хранятся ЦЕЛЫМИ в тех единицах, в которых их отдаёт датчик:
// влажность в целых процентах, температура в сотых долях градуса,
// напряжение в милливольтах. Плавающая точка не используется нигде —
// ни в разборе, ни в форматировании. Причина: форматирование с одним
// знаком после запятой должно быть побитово предсказуемым и совпадать с
// проверенной реализацией на Python, которая округляла десятичным
// Decimal с правилом «половина вверх». На double значение вида 26.95
// хранится как 26.9499999..., и printf("%.1f") даёт 26.9 вместо 27.0.
// Целочисленная арифметика такой расхождения не допускает.
struct Reading {
    uint8_t rh_percent;      // 0..100
    int16_t temp_centi_c;    // сотые доли градуса Цельсия
    uint16_t battery_mv;     // милливольты
};

}  // namespace rhcore

#pragma once
#include <stdint.h>

namespace rhcore {

// Что надо сделать с железом после очередного шага.
enum class Action {
    None,
    ResetBle,  // переинициализировать стек BLE: он залип
    Reboot,    // перезагрузить плату: слишком долго нет доставленных показаний
};

struct CycleConfig {
    // Период опроса датчика. Совпадает с серверным курьером.
    uint32_t interval_ms = 300000;  // 5 минут
    // Сколько неудачных чтений подряд означают залипший стек BLE. На
    // сервере тот же порог применялся к адаптеру Realtek, который
    // переставал отдавать пакеты сканирования.
    uint8_t failures_before_ble_reset = 3;
    // Сколько можно молчать до перезагрузки платы. Выбрано 20 минут при
    // сроке годности показания 30 минут: после перезагрузки остаётся два
    // полных периода опроса, чтобы доставить свежее показание ДО того,
    // как модуль на принтере погасит нагрев по протуханию. Если ставить
    // порог равным сроку годности, перезагрузка совпала бы с гашением и
    // ничего бы не спасала.
    uint32_t reboot_after_silence_ms = 1200000;  // 20 минут
};

// Состояние опросного цикла без всякого железа и без таймеров: время
// подаётся аргументом. Порт Feeder.run_once из
// feeder/ace_rh_feeder/main.py со счётчиком неудач подряд.
//
// Все сравнения времени сделаны через вычитание беззнаковых, поэтому
// переполнение millis() через 49.7 суток обрабатывается правильно и не
// приводит ни к зависанию цикла, ни к ложной перезагрузке.
class Cycle {
public:
    Cycle(const CycleConfig& cfg, uint32_t now_ms);

    // Пора ли делать очередной опрос. Самый первый опрос делается сразу.
    bool due(uint32_t now_ms) const;

    // Отметить начало опроса. Период отсчитывается от начала шага.
    void mark_started(uint32_t now_ms);

    // Датчик не прочитался. НИЧЕГО отправлять на принтер нельзя: старое
    // значение продлило бы срок годности и оставило нагрев включённым
    // вслепую.
    Action on_read_failed(uint32_t now_ms);

    // Показание прочитано и принято принтером.
    Action on_delivered(uint32_t now_ms);

    // Показание прочитано, но принтер его не принял. Счётчик неудач BLE не
    // растёт: датчик тут не виноват. Но молчание копится, и если оно
    // затянется, плата перезагрузится — это лечит зависший стек Wi-Fi,
    // который как раз и выглядит как недоступный принтер.
    Action on_not_delivered(uint32_t now_ms);

    uint8_t consecutive_failures() const { return failures_; }
    uint32_t silence_ms(uint32_t now_ms) const;

private:
    Action check_silence(uint32_t now_ms) const;

    CycleConfig cfg_;
    uint32_t last_start_ms_;
    uint32_t last_delivered_ms_;
    bool started_;
    uint8_t failures_;
};

}  // namespace rhcore

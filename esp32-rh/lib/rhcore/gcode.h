#pragma once
#include <stddef.h>
#include "reading.h"

namespace rhcore {

// Максимальная длина строки команды с запасом.
constexpr size_t kGcodeBufSize = 96;

// Собрать команду для Moonraker:
//   ACE_SET_RH ACE=0 RH=58.0 TTL=1800 TEMP=23.6
//
// Порт Moonraker.set_rh из feeder/ace_rh_feeder/moonraker.py. Оба числа с
// одним знаком после запятой. Округление температуры — «половина вверх по
// модулю», то есть от нуля: 23.65 -> 23.7, -23.65 -> -23.7. Считается на
// целых сотых долях, поэтому результат не зависит от представления double
// и одинаков на любой платформе.
//
// Влажность датчик отдаёт целым процентом, дробной части у неё нет и
// округлять нечего — выводится как "58.0".
//
// Возвращает число записанных символов без завершающего нуля, либо 0 при
// недостаточном буфере или негодных аргументах.
size_t build_set_rh(const Reading& r, int ace_index, int ttl_seconds,
                    char* buf, size_t buf_size);

// Округление сотых долей до десятых «половина от нуля». Вынесено в
// заголовок отдельно, потому что проверяется тестами прямо.
int16_t round_centi_to_deci(int16_t centi);

}  // namespace rhcore

#pragma once
#include <stdint.h>

#include "reading.h"

// Чтение Xiaomi LYWSD03MMC по BLE.
//
// Сток-прошивка датчика вещает показания в зашифрованном виде и требует
// ключ из облака Xiaomi, поэтому используется подключение GATT: оно отдаёт
// значения открытым текстом без облака и без ключа. То же решение принято
// в серверном курьере (feeder/ace_rh_feeder/sensor.py).
class BleSensor {
public:
    // Поднять стек BLE. Вызывается один раз при старте и повторно после
    // reset_stack().
    void begin();

    // Прочитать одно показание. Возвращает false, если датчик недоступен
    // или пакет негодный — это штатная ситуация, а не сбой: вызывающий
    // просто ничего не отправит принтеру.
    bool read(rhcore::Reading& out, uint32_t timeout_ms);

    // Полная переинициализация стека BLE. На сервере той же цели служил
    // перезапуск адаптера Realtek, который переставал отдавать пакеты,
    // оставаясь внешне исправным.
    void reset_stack();

private:
    bool inited_ = false;
};
